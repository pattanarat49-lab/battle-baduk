  // ladder reading: black (to move) captures the white group at tgt whatever white does
  const ladderMemo = new Map();
  function blackWins(b, tgt, d) {
    const libs = [...b.group(tgt).libs];
    if (libs.length === 1) return true;
    if (libs.length >= 3 || d > 14) return false;
    const key = b.a.join("") + tgt; if (ladderMemo.has(key)) return ladderMemo.get(key);
    if (ladderMemo.size > 20000) ladderMemo.clear();
    const res = blackWins2(b, tgt, d, libs); ladderMemo.set(key, res); return res;
  }
  function blackWins2(b, tgt, d, libs) {
    return libs.some(l => { const t = b.clone(), r = t.play(1, l); return r.ok && (!t.a[tgt] || (t.group(l).libs.size >= 1 && t.group(tgt).libs.size === 1 && whiteFails(t, tgt, d + 1))); });
  }
  // white to move with its group in atari: extending, or capturing a black stone next to it, all still lose
  function whiteMoves(b, tgt) {
    const g = b.group(tgt), out = new Set(g.libs);
    for (const s of g.stones) for (const k of nbs(s, b.N)) if (b.a[k] === 1) { const h = b.group(k); if (h.libs.size === 1) out.add([...h.libs][0]); }
    return [...out];
  }
  function whiteFails(b, tgt, d) { return whiteMoves(b, tgt).every(j => { const t = b.clone(), r = t.play(2, j); return !r.ok || blackWins(t, tgt, d + 1); }); }
  function runFrom(b, tgt) { return [...b.group(tgt).libs][0]; } // white runs along its last liberty
