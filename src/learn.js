  function sprinkle(b, n, fine) { for (let k = 0; k < n; k++) { const i = rnd(b.a.length); if (b.a[i]) continue; b.a[i] = 1 + rnd(2); if (!fine(b)) b.a[i] = 0; } }
  // one random puzzle with a checked answer
  function puzzle(mode, N) {
    for (let tries = 0; tries < 400; tries++) {
      const b = new Board(N); let p = null;
      if (mode === "eat" || mode === "save") { // one group (white: eat, black: save) left with a single liberty
        const tc = mode === "eat" ? 2 : 1, g = grow(b, tc, 1 + rnd(3)), libs = [...b.group(g[0]).libs]; if (libs.length < 2) continue;
        const keep = any(libs); for (const l of libs) if (l !== keep) b.a[l] = 3 - tc;
        const fine = b => !dead(b) && inAtari(b, tc) === 1 && !inAtari(b, 3 - tc) && b.group(g[0]).libs.size === 1;
        if (!fine(b)) continue; sprinkle(b, 2 + rnd(3), fine);
        p = { b, check: mode === "eat" ? i => { const r = b.clone().play(1, i); return r.ok && r.cap.length > 0; } : i => { const t = b.clone(), r = t.play(1, i); return r.ok && t.group(g[0]).libs.size >= 2; } };
      } else if (mode === "atari") { // a white group with two liberties: take one away, safely
        const g = grow(b, 2, 1 + rnd(2)), libs = [...b.group(g[0]).libs].sort(() => Math.random() - .5); if (libs.length < 3) continue;
        for (const l of libs.slice(2)) b.a[l] = 1;
        const fine = b => !dead(b) && !inAtari(b, 1) && !inAtari(b, 2) && b.group(g[0]).libs.size === 2;
        if (!fine(b)) continue; sprinkle(b, 1 + rnd(3), fine);
        p = { b, check: i => { const t = b.clone(), r = t.play(1, i); return r.ok && !r.cap.length && t.group(i).libs.size >= 2 && inAtari(t, 2) > 0; } };
      } else if (mode === "link") { // two black stones on a diagonal, white already on one of the two joints
        const x = 1 + rnd(N - 3), y = 1 + rnd(N - 3), q = [y * N + x, (y + 1) * N + x + 1, y * N + x + 1, (y + 1) * N + x], f = rnd(2) * 2, w = rnd(2);
        b.a[q[f]] = 1; b.a[q[f + 1]] = 1; b.a[q[(f + 2) % 4 + w]] = 2; const ans = q[(f + 2) % 4 + 1 - w];
        const fine = b => !dead(b) && !inAtari(b, 1) && !inAtari(b, 2) && !b.a[ans] && b.group(q[f]).stones.length === 1 && b.group(q[f + 1]).stones.length === 1;
        for (let k = 1 + rnd(3); k > 0; k--) { const i = rnd(b.a.length); if (b.a[i]) continue; b.a[i] = 2; if (!fine(b)) b.a[i] = 0; } // only white extras: the black pair stays obvious
        p = { b, check: i => i === ans };
      } else { // libs: count the liberties of the one black group
        const g = grow(b, 1, 1 + rnd(4));
        for (let k = rnd(3); k > 0; k--) { const libs = [...b.group(g[0]).libs]; if (libs.length > 1) b.a[any(libs)] = 2; }
        if (dead(b) || inAtari(b, 2)) continue;
        const n = b.group(g[0]).libs.size; if (n > 6) continue;
        const lo = Math.max(1, n - rnd(4)); p = { b, n, opts: [lo, lo + 1, lo + 2, lo + 3], lib: g[0] };
      }
      if (p.check && !p.b.a.some((v, i) => !v && p.check(i))) continue;
      p.mode = mode; return p;
    }
    return null;
  }
